export const qualityMetricsStatusSchema = z.enum(['draft', 'active', 'paused', 'completed', 'cancelled', 'archived']);
export const qualityMetricsPrioritySchema = z.enum(['low', 'normal', 'high', 'critical']);
export const qualityMetricsVisibilitySchema = z.enum(['private', 'care-team', 'facility', 'admin']);

export const qualityMetricsCreateSchema = z.object({
  title: z.string().min(2).max(200),
  description: z.string().min(1).max(5000),
  status: qualityMetricsStatusSchema.optional(),
  priority: qualityMetricsPrioritySchema.optional(),
  visibility: qualityMetricsVisibilitySchema.optional(),
  residentId: z.string().min(1),
  caregiverId: z.string().min(1).optional(),
  tags: z.array(z.string().max(40)).max(25).optional(),
  notes: z.array(z.string().max(1000)).max(50).optional(),
  metadata: z.record(z.union([z.string(), z.number(), z.boolean(), z.null()])).optional(),
});

export const qualityMetricsUpdateSchema = qualityMetricsCreateSchema.partial().extend({
  id: z.string().min(1),
});

export const qualityMetricsFilterSchema = z.object({
  status: z.array(qualityMetricsStatusSchema).optional(),
  priority: z.array(qualityMetricsPrioritySchema).optional(),
  residentId: z.string().optional(),
  caregiverId: z.string().optional(),
  query: z.string().max(200).optional(),
  from: z.string().optional(),
  to: z.string().optional(),
  page: z.number().int().min(1).optional(),
  pageSize: z.number().int().min(1).max(200).optional(),
  sortBy: z.string().optional(),
  sortDir: z.enum(['asc', 'desc']).optional(),
});

