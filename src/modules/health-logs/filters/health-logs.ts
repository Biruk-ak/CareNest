import type { HealthLogsFilter, HealthLogsRecord } from '../types/health-logs';

export function applyHealthLogsQuickFilters(items: HealthLogsRecord[], mode: 'all' | 'active' | 'critical' | 'mine', actorId?: string): HealthLogsRecord[] {
  switch (mode) {
    case 'active':
      return items.filter((i) => i.status === 'active');
    case 'critical':
      return items.filter((i) => i.priority === 'critical' || i.priority === 'high');
    case 'mine':
      return items.filter((i) => i.caregiverId === actorId || i.createdBy === actorId);
    default:
      return items;
  }
}

export function mergeHealthLogsFilters(base: HealthLogsFilter, patch: Partial<HealthLogsFilter>): HealthLogsFilter {
  return { ...base, ...patch };
}

export function rankHealthLogsRelevance1(item: HealthLogsRecord, query: string): number {
  if (!query) return 0;
  const q = query.toLowerCase();
  let score = 1;
  if (item.title.toLowerCase().includes(q)) score += 50;
  if (item.description.toLowerCase().includes(q)) score += 20;
  if (item.tags.some((t) => t.toLowerCase().includes(q))) score += 15;
  if (item.priority === 'critical') score += 10;
  return score;
}

