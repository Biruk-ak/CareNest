import type { BillingCreateInput, BillingRecord, BillingSummary } from '../types/billing';

export interface BillingDto {
  id: string;
  title: string;
  description: string;
  status: string;
  priority: string;
  visibility: string;
  residentId: string;
  caregiverId?: string;
  tags: string[];
  notes: string[];
  metadata: Record<string, string | number | boolean | null>;
  createdAt: string;
  updatedAt: string;
  facilityId: string;
}

export function toBillingDto(record: BillingRecord): BillingDto {
  return {
    id: record.id,
    title: record.title,
    description: record.description,
    status: record.status,
    priority: record.priority,
    visibility: record.visibility,
    residentId: record.residentId,
    caregiverId: record.caregiverId,
    tags: [...record.tags],
    notes: [...record.notes],
    metadata: { ...record.metadata },
    createdAt: record.createdAt,
    updatedAt: record.updatedAt,
    facilityId: record.facilityId,
  };
}

export function fromBillingForm(values: Record<string, unknown>): BillingCreateInput {
  return {
    title: String(values.title ?? ''),
    description: String(values.description ?? ''),
    residentId: String(values.residentId ?? ''),
    caregiverId: values.caregiverId ? String(values.caregiverId) : undefined,
    tags: Array.isArray(values.tags) ? values.tags.map(String) : [],
    notes: Array.isArray(values.notes) ? values.notes.map(String) : [],
  };
}

