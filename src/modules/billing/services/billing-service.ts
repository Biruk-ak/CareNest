  constructor(private readonly store = billingStore) {}

  async list(filter: BillingFilter = {}): Promise<BillingPage> {
    const parsed = billingFilterSchema.parse(filter);
    const all = this.store.getAll();
    const filtered = all.filter((item) => matchesBillingFilter(item, parsed));
    return paginateBilling(filtered, parsed.page ?? 1, parsed.pageSize ?? 25, parsed.sortBy as keyof BillingRecord | undefined, parsed.sortDir);
  }

  async getById(id: BillingId): Promise<BillingRecord | null> {
    return this.store.getById(id) ?? null;
  }

  async create(input: BillingCreateInput, actorId: string, facilityId: string): Promise<BillingRecord> {
    const data = billingCreateSchema.parse(input);
    const stamp = nowIso();
    const record: BillingRecord = {
      id: buildBillingId(),
      title: data.title,
      description: data.description,
      status: data.status ?? 'draft',
      priority: data.priority ?? 'normal',
      visibility: data.visibility ?? 'care-team',
      residentId: data.residentId,
      caregiverId: data.caregiverId,
      tags: data.tags ?? [],
      notes: data.notes ?? [],
      metadata: data.metadata ?? {},
      createdAt: stamp,
      updatedAt: stamp,
      createdBy: actorId,
      updatedBy: actorId,
      version: 1,
      facilityId,
    };
    this.store.upsert(record);
    return record;
  }

  async update(input: BillingUpdateInput, actorId: string): Promise<BillingRecord> {
    const data = billingUpdateSchema.parse(input);
    const existing = this.store.getById(data.id as BillingId);
    if (!existing) throw new Error('Billing record not found');
    const next: BillingRecord = {
      ...existing,
      ...data,
      id: existing.id,
      updatedAt: nowIso(),
      updatedBy: actorId,
      version: existing.version + 1,
      tags: data.tags ?? existing.tags,
      notes: data.notes ?? existing.notes,
      metadata: data.metadata ?? existing.metadata,
    };
    this.store.upsert(next);
    return next;
  }

  async remove(id: BillingId): Promise<boolean> {
    return this.store.remove(id);
  }

  async summary(facilityId?: string): Promise<BillingSummary> {
    const items = this.store.getAll().filter((r) => !facilityId || r.facilityId === facilityId);
    const weekAgo = Date.now() - 7 * 24 * 60 * 60 * 1000;
    return {
      total: items.length,
      active: items.filter((i) => i.status === 'active').length,
      critical: items.filter((i) => i.priority === 'critical').length,
      completedThisWeek: items.filter((i) => i.status === 'completed' && new Date(i.updatedAt).getTime() >= weekAgo).length,
      overdue: items.filter((i) => i.status === 'active' && i.priority === 'high').length,
    };
  }

