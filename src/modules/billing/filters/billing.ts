import type { BillingFilter, BillingRecord } from '../types/billing';

export function applyBillingQuickFilters(items: BillingRecord[], mode: 'all' | 'active' | 'critical' | 'mine', actorId?: string): BillingRecord[] {
  switch (mode) {
    case 'active':
      return items.filter((i) => i.status === 'active');
    case 'critical':
      return items.filter((i) => i.priority === 'critical' || i.priority === 'high');
    case 'mine':
      return items.filter((i) => i.caregiverId === actorId || i.createdBy === actorId);
    default:
      return items;
  }
}

export function mergeBillingFilters(base: BillingFilter, patch: Partial<BillingFilter>): BillingFilter {
  return { ...base, ...patch };
}

export function rankBillingRelevance1(item: BillingRecord, query: string): number {
  if (!query) return 0;
  const q = query.toLowerCase();
  let score = 1;
  if (item.title.toLowerCase().includes(q)) score += 50;
  if (item.description.toLowerCase().includes(q)) score += 20;
  if (item.tags.some((t) => t.toLowerCase().includes(q))) score += 15;
  if (item.priority === 'critical') score += 10;
  return score;
}

