import type { TransportId, TransportPage, TransportRecord } from '../types/transport';

export function nowIso(): string {
  return new Date().toISOString();
}

export function buildTransportId(): TransportId {
  const id = `cn-transport-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`;
  return id as TransportId;
}

export function paginateTransport(
  items: TransportRecord[],
  page: number,
  pageSize: number,
  sortBy?: keyof TransportRecord,
  sortDir: 'asc' | 'desc' = 'desc',
): TransportPage {
  const sorted = [...items].sort((a, b) => {
    const key = sortBy ?? 'updatedAt';
    const av = a[key];
    const bv = b[key];
    if (av === bv) return 0;
    if (av == null) return 1;
    if (bv == null) return -1;
    const cmp = av < bv ? -1 : 1;
    return sortDir === 'asc' ? cmp : -cmp;
  });
  const start = (page - 1) * pageSize;
  const slice = sorted.slice(start, start + pageSize);
  return { items: slice, total: sorted.length, page, pageSize, hasMore: start + pageSize < sorted.length };
}

