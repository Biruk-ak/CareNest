  constructor(private readonly store = caregiversStore) {}

  async list(filter: CaregiversFilter = {}): Promise<CaregiversPage> {
    const parsed = caregiversFilterSchema.parse(filter);
    const all = this.store.getAll();
    const filtered = all.filter((item) => matchesCaregiversFilter(item, parsed));
    return paginateCaregivers(filtered, parsed.page ?? 1, parsed.pageSize ?? 25, parsed.sortBy as keyof CaregiversRecord | undefined, parsed.sortDir);
  }

  async getById(id: CaregiversId): Promise<CaregiversRecord | null> {
    return this.store.getById(id) ?? null;
  }

  async create(input: CaregiversCreateInput, actorId: string, facilityId: string): Promise<CaregiversRecord> {
    const data = caregiversCreateSchema.parse(input);
    const stamp = nowIso();
    const record: CaregiversRecord = {
      id: buildCaregiversId(),
      title: data.title,
      description: data.description,
      status: data.status ?? 'draft',
      priority: data.priority ?? 'normal',
      visibility: data.visibility ?? 'care-team',
      residentId: data.residentId,
      caregiverId: data.caregiverId,
      tags: data.tags ?? [],
      notes: data.notes ?? [],
      metadata: data.metadata ?? {},
      createdAt: stamp,
      updatedAt: stamp,
      createdBy: actorId,
      updatedBy: actorId,
      version: 1,
      facilityId,
    };
    this.store.upsert(record);
    return record;
  }

  async update(input: CaregiversUpdateInput, actorId: string): Promise<CaregiversRecord> {
    const data = caregiversUpdateSchema.parse(input);
    const existing = this.store.getById(data.id as CaregiversId);
    if (!existing) throw new Error('Caregivers record not found');
    const next: CaregiversRecord = {
      ...existing,
      ...data,
      id: existing.id,
      updatedAt: nowIso(),
      updatedBy: actorId,
      version: existing.version + 1,
      tags: data.tags ?? existing.tags,
      notes: data.notes ?? existing.notes,
      metadata: data.metadata ?? existing.metadata,
    };
    this.store.upsert(next);
    return next;
  }

  async remove(id: CaregiversId): Promise<boolean> {
    return this.store.remove(id);
  }

  async summary(facilityId?: string): Promise<CaregiversSummary> {
    const items = this.store.getAll().filter((r) => !facilityId || r.facilityId === facilityId);
    const weekAgo = Date.now() - 7 * 24 * 60 * 60 * 1000;
    return {
      total: items.length,
      active: items.filter((i) => i.status === 'active').length,
      critical: items.filter((i) => i.priority === 'critical').length,
      completedThisWeek: items.filter((i) => i.status === 'completed' && new Date(i.updatedAt).getTime() >= weekAgo).length,
      overdue: items.filter((i) => i.status === 'active' && i.priority === 'high').length,
    };
  }

